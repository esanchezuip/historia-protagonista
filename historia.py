# Solicitar datos al usuario
nombre = input("Ingresa tu nombre: ")
edad = int(input("Ingresa tu edad: "))
ciudad = input("Ingresa tu ciudad de residencia: ")

# Mostrar el saludo personalizado
print(f"¡Hola, {nombre}! Tienes {edad} años y vives en {ciudad}.")

# Inicio de la historia (Eliab)
print(f"Una mañana en {ciudad}, {nombre} despertó con la sensación de que ese día sería diferente.")

# Continuación de la historia (Gian)
print(f"Teniendo tan solo {edad}, se volveria el aventurero exitoso mas joven de la historia...")
print(f"Luego lo atropello un camion y no paramedicos no lograron llegar al hospital a tiempo.")
print(f"El fin.")
